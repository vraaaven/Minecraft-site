    Однако, они решили двигаться дальше.
    Их решением было отправиться в новый мир, поставив себе цели на общую колонию и коллекцию из всех драконов.
    В целом, они в этом преуспели: развили неплохую колонию и заимели многих драконов (<a href="https://www.twitch.tv/oleksagompers/clip/InnocentKindDotterelFunRun-E7PSa-587CJ2bl_E" rel="nofollow" target="_blank">правда, иногда случались неловкие инциденты по скрещиванию драконов</a>).
