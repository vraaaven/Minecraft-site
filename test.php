<p>Давным-давно еще до существования сервера, основатели <span>vraven</span> и <span>OleksaGompers</span> выживали
    вдвоем.</p>
<p>Они побывали в двух мира. В первом OleksaGompers начала изучать мир Майнкрафта и особенности сборки...
    Ей довелось повстречать разнообразных существ, сразиться с монстрами и даже заиметь драконов <br>
    (<a href="https://www.twitch.tv/oleksagompers/clip/CrazyAbstemiousAnacondaUncleNox-HjTCF3L1pv4p_QAV" rel="nofollow" target="_blank">иногда прилетало не только монстрам</a>).
</p>
<p>
    Они начали выживать в биоме с сакурой в небольшом японским домике.
    Со временем они захотели переехать и vraven начал постройку особняка в лесу  (<a href="https://www.twitch.tv/videos/2066319294" rel="nofollow" target="_blank">здесь можно немного лицезреть домик и начальное выживанание</a>).
    В то же время Олекса пушествовала по миру и в один из дней нашла заброшенную японскую колонию.
    И тогда началось ее изучение колоний. Вравен учил ее всем хитростям развития колонии и всё то, что знал сам.
</p>
